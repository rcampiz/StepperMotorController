"""Generate the LCD's 8x12 and 12x16 glyph tables from a TrueType font, rendered 1-bit
(no anti-aliasing) so every pixel is deliberate, plus a preview PNG.

    python scripts/lcd/gen_fonts.py [preview.png]

Writes server/layers/L4_drivers/devices/font_8x12.hpp and font_12x16.hpp: ASCII 32..126,
one byte per row for the 8-wide font (bit 7 = leftmost pixel), one uint16 per row for the
12-wide one (bit 15 = leftmost). The cells keep a blank right column and a blank bottom
column so adjacent characters do not touch; descenders may use the last row.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_DIR = os.path.join(ROOT, "server", "layers", "L4_drivers", "devices")

FONTS = [
    # name, ttf, px size, cell w, cell h, baseline row (from top), header file
    ("FONT_8X12", "C:/Windows/Fonts/consola.ttf", 13, 8, 12, 10, "font_8x12.hpp"),
    ("FONT_12X16", "C:/Windows/Fonts/consolab.ttf", 18, 12, 16, 13, "font_12x16.hpp"),
]


def render_glyph(font, ch, cw, chh, baseline):
    """1-bit cell: the glyph's baseline on `baseline`, left-aligned with 0 px margin."""
    im = Image.new("1", (cw * 3, chh * 3), 0)
    d = ImageDraw.Draw(im)
    ascent, _descent = font.getmetrics()
    ox, oy = cw, chh                                   # draw in the middle third
    d.text((ox, oy + baseline - ascent), ch, font=font, fill=1)
    # Crop the cell: ink left edge aligned to column 0 (monospace advance keeps spacing)
    bbox = im.getbbox()
    rows = []
    for y in range(chh):
        row = 0
        for x in range(cw):
            if im.getpixel((ox + x, oy + y)):
                row |= 1 << (cw - 1 - x)
        rows.append(row)
    clipped = False
    if bbox:
        x0, y0, x1, y1 = bbox
        clipped = x1 > ox + cw - 1 or y0 < oy or y1 > oy + chh - 1   # last column kept blank
    return rows, clipped


def main():
    preview = sys.argv[1] if len(sys.argv) > 1 else None
    previews = []
    for name, ttf, size, cw, chh, baseline, header in FONTS:
        font = ImageFont.truetype(ttf, size)
        glyphs = []
        clipped = []
        for code in range(32, 127):
            rows, clip = render_glyph(font, chr(code), cw, chh, baseline)
            # the last column is spacing: clear it
            rows = [r & ~1 for r in rows]
            glyphs.append(rows)
            if clip:
                clipped.append(chr(code))
        fmt = "0x%02X" if cw <= 8 else "0x%04X"
        ctype = "uint8_t" if cw <= 8 else "uint16_t"
        lines = ["/**", " * @file %s" % header,
                 " * @brief GENERATED by scripts/lcd/gen_fonts.py from %s at %d px, 1-bit." % (os.path.basename(ttf), size),
                 " *        ASCII 32..126, %d x %d cells, one %s per row, high bit = leftmost pixel." % (cw, chh, ctype),
                 " *        Do not edit: rerun the script." " */", "#pragma once", "#include <stdint.h>", "",
                 "static const %s %s[95][%d] = {" % (ctype, name, chh)]
        for i, rows in enumerate(glyphs):
            ch = chr(32 + i)
            label = ch if ch not in ("\\", "*/", "/*") else "ch"
            lines.append("    {%s}, // %d '%s'" % (", ".join(fmt % r for r in rows), 32 + i, label.replace("'", "\\'")))
        lines.append("};")
        lines.append("")
        path = os.path.join(OUT_DIR, header)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(lines))
        print("wrote", path, "clipped:", "".join(clipped) or "none")
        previews.append((name, cw, chh, glyphs))

    if preview:
        text = "Encoder Motion 0123 Telemetry rpm Hi-Z POS 1366 cnt @#%&{}[]|/\\ gjpqy"
        scale = 3
        h = sum(chh * scale + 24 for _, _, chh, _ in previews)
        sheet = Image.new("RGB", (len(text) * 12 * scale, h), (8, 8, 16))
        y = 0
        for name, cw, chh, glyphs in previews:
            ImageDraw.Draw(sheet).text((4, y), name, fill=(120, 140, 170))
            y += 16
            for i, ch in enumerate(text):
                rows = glyphs[ord(ch) - 32]
                for r, bits in enumerate(rows):
                    for c in range(cw):
                        if bits & (1 << (cw - 1 - c)):
                            x0, y0 = (i * cw + c) * scale, y + r * scale
                            for dy in range(scale):
                                for dx in range(scale):
                                    sheet.putpixel((x0 + dx, y0 + dy), (216, 228, 240))
            y += chh * scale + 8
        sheet.save(preview)
        print("wrote", preview)


if __name__ == "__main__":
    main()
