"""Generate tests/fakes/fake_dispatchers.hpp: a no-op implementation of every L3 dispatcher
interface plus a ready-made Harness::L3Dispatchers bundle, so parser-level host tests can
drive commands that reach L3. Each fake records the last call name in `calls`."""
import pathlib, re
R = pathlib.Path(r"C:\Users\campi\StepperMotorController")
B = R / "server/layers/L3_services/boundary"
IFACES = [
    ("imotion_dispatcher", "IMotionDispatcher", "motion"),
    ("imotor_config_dispatcher", "IMotorConfigDispatcher", "config"),
    ("isafety_dispatcher", "ISafetyDispatcher", "safety"),
    ("iqueue_dispatcher", "IQueueDispatcher", "queue"),
    ("icontrol_mode_dispatcher", "IControlModeDispatcher", "controlMode"),
    ("isupervisor_trim_dispatcher", "ISupervisorTrimDispatcher", "supervisorTrim"),
    ("iencoder_dispatcher", "IEncoderDispatcher", "encoder"),
    ("imotor_driver_dispatcher", "IMotorDriverDispatcher", "motorDriver"),
    ("idisplay_dispatcher", "IDisplayDispatcher", "display"),
    ("iflash_image_dispatcher", "IFlashImageDispatcher", "flash"),
    ("isystem_dispatcher", "ISystemDispatcher", "system"),
    ("itrace_dispatcher", "ITraceDispatcher", "trace"),
    ("idebug_dispatcher", "IDebugDispatcher", "debug"),
]
SCALARS = {'bool', 'char', 'int', 'unsigned', 'long', 'float', 'double', 'size_t',
           'int8_t', 'int16_t', 'int32_t', 'int64_t', 'uint8_t', 'uint16_t', 'uint32_t', 'uint64_t'}
PURE = re.compile(r'virtual\s+([\w:<>\*&\s]+?)\s+(\w+)\s*\(([^)]*)\)\s*(const)?\s*=\s*0\s*;', re.S)

out = ['/**',
       ' * @file fake_dispatchers.hpp',
       ' * @brief GENERATED by scripts/gen_fake_dispatchers.py (rerun after changing an L3 dispatcher interface): no-op fakes for the 13 L3 dispatcher',
       ' *        interfaces and a Harness::L3Dispatchers bundle. Every method records its name in `calls`;',
       ' *        return values are value-initialised (0 / false / Ok / empty). Tests override what they need.',
       ' */',
       '#pragma once',
       '#pragma GCC diagnostic push',
       '#pragma GCC diagnostic ignored "-Wunused-parameter"   // fakes ignore their arguments by design',
       '#include "harness/defs/harness_l2_l3.hpp"',
       '#include <string>', '#include <vector>', '', 'namespace FakeL3 {', 'using namespace Services;   // namespace-scope types used by the interfaces (DebugDispatchResult, ...)', '']
for fname, iface, member in IFACES:
    text = (B / (fname + ".hpp")).read_text(encoding="utf-8")
    cls = "Fake" + iface[1:]
    out.append("struct %s : Services::%s {" % (cls, iface))
    out.append("    mutable std::vector<std::string> calls;")
    for m in PURE.finditer(text):
        ret, name, args, const = m.group(1).strip(), m.group(2), " ".join(m.group(3).split()), m.group(4) or ""
        # strip default arguments from the override signature
        args = re.sub(r'\s*=\s*[^,)]+', '', args)
        body = "calls.push_back(\"%s\");" % name
        # non-const reference parameters are out-params: value-initialise them so callers never read garbage
        for am in re.finditer(r'([\w:]+(?:<[^>]*>)?)\s*&\s*(\w+)', args):
            if am.group(1) in SCALARS and not re.search(r'const\s+' + re.escape(am.group(1)) + r'\s*&\s*' + am.group(2), args):
                body += " %s = %s{};" % (am.group(2), am.group(1))
        if ret == "void":
            out.append("    void %s(%s) %s override { %s }" % (name, args, const, body))
        elif ret.endswith("*") and ret not in ("const char*", "const char *"):
            out.append("    %s %s(%s) %s override { %s return nullptr; }" % (ret, name, args, const, body))
        elif ret in ("const char*", "const char *"):
            out.append("    %s %s(%s) %s override { %s return \"\"; }" % (ret, name, args, const, body))
        else:
            out.append("    %s %s(%s) %s override { %s return %s{}; }" % (ret, name, args, const, body, ret))
    out.append("};")
    out.append("")
out.append("/// One of each fake plus the bundle the ServiceDispatcher binds to.")
out.append("struct Bundle {")
for fname, iface, member in IFACES:
    out.append("    Fake%s %s;" % (iface[1:], member))
out.append("    Harness::L3Dispatchers dispatchers{" + ", ".join(m for _, _, m in IFACES) + "};")
out.append("};")
out.append("")
out.append("} // namespace FakeL3")
out.append("#pragma GCC diagnostic pop")
(R / "tests/fakes/fake_dispatchers.hpp").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print("wrote tests/fakes/fake_dispatchers.hpp with", sum(1 for _ in out if " override " in _), "methods")
